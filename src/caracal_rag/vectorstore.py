from __future__ import annotations

import uuid
from dataclasses import dataclass
from typing import Iterable

from chromadb import HttpClient

from caracal_rag.chunking import Chunk


@dataclass(frozen=True)
class ChunkRecord:
    chunk_id: str
    text: str
    embedding: list[float]
    metadata: dict


def _chroma_client(host: str, port: int, ssl: bool) -> HttpClient:
    return HttpClient(host=host, port=int(port), ssl=bool(ssl))


def ensure_collection(client: HttpClient, name: str) -> any:
    return client.get_or_create_collection(name=name)


def _chunk_id(chunk: Chunk) -> str:
    """Deterministic chunk id derived from the document url and chunk index.

    Using a stable id makes repeated indexing idempotent: re-upserting the same
    chunk overwrites the previous vector instead of duplicating it.
    """
    return str(uuid.uuid5(uuid.NAMESPACE_DNS, f"{chunk.url}-{chunk.chunk_index}"))


def upsert_chunks(
    collection,
    chunks: Iterable[Chunk],
    embeddings: list[list[float]],
    embedding_model: str,
    ids: list[str] | None = None,
    staging: bool = False,
    embedding_dim: int | None = None,
) -> None:
    """Insert or update chunk vectors.

    Chunks are keyed by a deterministic id (document url + chunk index), so
    re-running indexing on unchanged documents overwrites the previous vector.
    The embedding model is persisted with each row to guard against mixing
    embedding spaces.

    Temporary replacement writes pass staging=True. Those rows carry an
    explicit caracal_staging marker so search and embedding-model consistency
    checks can exclude them until promotion succeeds.
    """
    chunk_ids = list(ids) if ids is not None else [_chunk_id(chunk) for chunk in chunks]
    documents: list[str] = []
    metadatas: list[dict] = []
    for idx, chunk in enumerate(chunks):
        documents.append(chunk.text)
        metadatas.append(
            {
                "source": chunk.source,
                "document": chunk.document,
                "url": chunk.url,
                "type": chunk.type,
                "content_hash": chunk.content_hash,
                "chunk_index": chunk.chunk_index,
                "embedding_model": embedding_model,
                "embedding_dim": embedding_dim,
                "caracal_staging": staging,
            }
        )
    if not chunk_ids:
        return
    collection.upsert(
        ids=chunk_ids,
        documents=documents,
        embeddings=embeddings,
        metadatas=metadatas,
    )


def delete_document_chunks(collection, document_url: str) -> None:
    """Delete all chunks belonging to a document url."""
    results = collection.get(where={"url": document_url}, include=["metadatas"])
    ids = results.get("ids") or []
    if ids:
        collection.delete(ids=ids)


def delete_missing_documents(
    collection,
    current_urls: Iterable[str],
    source: str | None = None,
) -> list[str]:
    """Remove chunks whose document url is no longer present in the source.

    Returns the list of removed document urls. This keeps the index consistent
    when source documents are deleted between indexing runs.

    When ``source`` is provided, only chunks from that source are considered
    for deletion, so indexing a single source never removes vectors from other
    configured sources.
    """
    current = set(current_urls)
    # Request metadatas explicitly: Chroma does not return metadata unless it is
    # asked for, so stale vectors would otherwise go undetected.
    existing = collection.get(include=["metadatas"])
    ids = existing.get("ids") or []
    metadatas = existing.get("metadatas") or []

    stale_urls: set[str] = set()
    stale_ids: list[str] = []
    for chunk_id, metadata in zip(ids, metadatas):
        url = (metadata or {}).get("url")
        if url and url not in current:
            if source is not None and (metadata or {}).get("source") != source:
                continue
            stale_urls.add(url)
            stale_ids.append(chunk_id)

    if stale_ids:
        collection.delete(ids=stale_ids)
    return sorted(stale_urls)


def get_existing_chunks(collection) -> dict[str, dict]:
    """Return a mapping of chunk id -> metadata for every chunk in the collection."""
    existing = collection.get(include=["metadatas"])
    ids = existing.get("ids") or []
    metadatas = existing.get("metadatas") or []
    return {chunk_id: metadata or {} for chunk_id, metadata in zip(ids, metadatas)}


def collection_embedding_models(collection) -> set[str]:
    """Return the set of embedding models persisted in the collection's metadata.

    Used to detect when the configured embedding model changes: vectors from a
    different embedding space must never be mixed with query vectors generated by
    the current model. Vectors that carry no ``embedding_model`` metadata are
    *not* counted here; :func:`assert_embedding_model_consistent` (via
    :func:`collection_is_legacy`) refuses collections that still hold them.
    """
    existing = collection.get(include=["metadatas"])
    metadatas = existing.get("metadatas") or []
    models: set[str] = set()
    for metadata in metadatas:
        if not metadata or metadata.get("caracal_staging", False):
            continue
        model = metadata.get("embedding_model")
        if model:
            models.add(model)
    return models


def collection_is_legacy(collection) -> bool:
    """Return True when the collection holds vectors but any lacks model metadata.

    A legacy collection (created before model tracking existed, or populated
    outside the indexer) has vectors but no ``embedding_model`` field, so its
    embedding space is unknown and must never be silently mixed with query
    vectors from the configured model. An empty collection has no vectors at all
    and therefore is not legacy -- the first indexing run establishes the
    collection-level model invariant.

    A *mixed* collection (some vectors tagged with ``embedding_model``, others
    not) is refused too. Previously only a fully untagged collection was treated
    as legacy, so a collection with even one tagged vector was accepted while it
    still held vectors from an unknown embedding space -- those untagged vectors
    could then be returned by search or re-used by indexing next to query
    vectors from the configured model. Any vector that lacks model metadata makes
    the whole collection unsafe to use.
    """
    existing = collection.get(include=["metadatas"])
    metadatas = existing.get("metadatas") or []
    committed_metadatas = [
        metadata or {}
        for metadata in metadatas
        if not (metadata or {}).get("caracal_staging", False)
    ]
    if not committed_metadatas:
        # A collection containing only temporary replacement rows has no
        # committed embedding space to validate. Indexing can safely retry.
        return False
    return not all(metadata.get("embedding_model") for metadata in committed_metadatas)


def assert_embedding_model_consistent(collection, model: str) -> None:
    """Raise ``ValueError`` if the collection holds vectors from another model.

    Vectors from a different embedding space must never be mixed with query
    vectors generated by the configured model -- the similarity scores would be
    meaningless. Four cases are distinguished:

    * Empty collection (no vectors yet) -- always consistent; the first indexing
      run establishes the collection-level model invariant.
    * Legacy or mixed collection (vectors exist but some lack ``embedding_model``
      metadata) -- the embedding space of the untagged vectors is unknown, so
      refuse to index or search rather than risk mixing spaces. A rebuild with
      the current model is required.
    * Collection already tagged with the configured model -- consistent.
    * Collection tagged with a different model -- raise with rebuild guidance.
    """
    if collection_is_legacy(collection):
        raise ValueError(
            "Collection holds vectors with no embedding_model metadata, so its "
            "embedding space is unknown. Rebuild the index with the current "
            f"model ({model!r}) or point the configuration at a separate collection."
        )
    stored = collection_embedding_models(collection)
    if not stored:
        return
    if stored == {model}:
        return
    raise ValueError(
        f"Collection vectors were embedded with model(s) {sorted(stored)!r}, "
        f"but the configuration requests model {model!r}. Mixing embedding spaces "
        "produces meaningless search results. Rebuild the index with the current "
        "model or point the configuration at a separate collection."
    )


def collection_embedding_dim(collection) -> int | None:
    """Return the dimension of the vectors stored in the collection.

    The dimension is read from the committed chunk metadata first (the fast
    path, written by every upsert since dimension tracking existed). When no
    committed row carries it -- a legacy collection built before dimension
    tracking -- the stored vectors themselves are inspected as a fallback so
    the dimension can still be derived without re-embedding.

    Returns ``None`` when the collection holds no committed vectors at all
    (an empty or staging-only collection has no recorded embedding space).

    Raises ``ValueError`` when committed rows disagree on dimension, i.e. the
    collection holds vectors from two different embedding spaces. Such a
    mixed collection is unsafe to index or search against and must be rebuilt.
    """
    existing = collection.get(include=["metadatas", "embeddings"])
    metadatas = existing.get("metadatas") or []
    embeddings = existing.get("embeddings") or []

    committed: list[dict] = []
    for metadata, vector in zip(metadatas, embeddings):
        if not (metadata or {}).get("caracal_staging", False):
            committed.append({"metadata": metadata or {}, "vector": vector})

    if not committed:
        return None

    dims: set[int] = set()
    for record in committed:
        dim = (record["metadata"] or {}).get("embedding_dim")
        if dim is None:
            vector = record["vector"]
            if vector is None:
                raise ValueError(
                    "Collection holds committed vectors with no embedding_dim "
                    "metadata and no retrievable vector to derive it from; the "
                    "embedding space is unknown. Rebuild the index with the "
                    "current model or point the configuration at a separate "
                    "collection."
                )
            dim = len(vector)
        if not isinstance(dim, int) or dim <= 0:
            raise ValueError(
                "Collection holds committed vectors with an invalid "
                f"embedding_dim {dim!r}; the embedding space is unknown. Rebuild "
                "the index with the current model or point the configuration at "
                "a separate collection."
            )
        dims.add(dim)
    if len(dims) > 1:
        raise ValueError(
            f"Collection holds committed vectors from {sorted(dims)!r}-"
            "dimensional embedding spaces. Mixing dimensions produces "
            "meaningless search results. Rebuild the index with the current "
            "model or point the configuration at a separate collection."
        )
    return next(iter(dims))


def assert_embedding_dim_consistent(collection, observed_dim: int) -> None:
    """Raise ``ValueError`` when the stored vectors disagree with the live probe.

    The configured model is probed once and the resulting dimension is compared
    against the collection's stored dimension. An empty collection has no
    stored vectors yet, so there is nothing to mix and the first indexing run
    establishes the dimension invariant.
    """
    stored = collection_embedding_dim(collection)
    if stored is None:
        return
    if stored == observed_dim:
        return
    raise ValueError(
        f"Collection vectors are {stored}-dimensional but the configured "
        f"embedding model produces {observed_dim}-dimensional vectors. Mixing "
        "embedding spaces produces meaningless search results. Rebuild the "
        "index with the current model or point the configuration at a separate "
        "collection."
    )


def _contains_staging_results(response: dict) -> bool:
    """Return True when a Chroma query result contains a temporary row."""
    for group in response.get("metadatas") or []:
        metadata_rows = group if isinstance(group, list) else [group]
        if any(
            isinstance(metadata, dict) and metadata.get("caracal_staging", False)
            for metadata in metadata_rows
        ):
            return True
    return False


def _without_staging_results(response: dict, top_k: int) -> dict:
    """Filter temporary rows from nested Chroma results, preserving field alignment."""
    filtered = dict(response)
    metadata_groups = response.get("metadatas") or []
    for field in ("ids", "documents", "metadatas", "distances"):
        groups = response.get(field)
        if not isinstance(groups, list):
            continue
        filtered_groups = []
        for query_index, values in enumerate(groups):
            if not isinstance(values, list):
                filtered_groups.append(values)
                continue
            metadata_values = (
                metadata_groups[query_index]
                if query_index < len(metadata_groups)
                else []
            )
            if not isinstance(metadata_values, list):
                metadata_values = [metadata_values]
            keep = [
                index
                for index, metadata in enumerate(metadata_values)
                if not (
                    isinstance(metadata, dict)
                    and metadata.get("caracal_staging", False)
                )
            ]
            filtered_groups.append(
                [values[index] for index in keep if index < len(values)][:top_k]
            )
        filtered[field] = filtered_groups
    return filtered


def search_chunks(collection, query_embedding: list[float], top_k: int = 5):
    """Search committed chunks only, including during recovery from a failed index run.

    The usual top-k query is fast. When a temporary row occupies one of those
    results, expand to the full collection result count, then filter temporary
    rows. This preserves top-k semantics without a metadata filter that could
    unintentionally hide older committed rows lacking the staging marker.
    """
    response = collection.query(
        query_embeddings=[query_embedding],
        n_results=top_k,
    )
    if not _contains_staging_results(response):
        return response

    all_rows = collection.get(include=["metadatas"])
    total = len(all_rows.get("ids") or [])
    if total > top_k:
        response = collection.query(
            query_embeddings=[query_embedding],
            n_results=total,
        )
    return _without_staging_results(response, top_k)
